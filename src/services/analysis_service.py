"""Orchestrates one AI analysis run and persists every artefact it produces.

Pipeline: retrieve -> generate -> extract claims -> validate evidence ->
detect contradictions -> compute metrics -> persist -> audit.

Each stage writes its own audit event, so the trail reconstructs what the
system did, in order, with what inputs.
"""
