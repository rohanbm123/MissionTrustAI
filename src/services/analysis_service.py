def load_latest_assessment(case_id: str) -> Optional[FinalCaseAssessment]:
    """The most recent shipped recommendation for a case, if any."""
    with session_scope() as session:
        analysis = AnalysisRepository.latest_for_case(session, case_id)
        if analysis is None or not analysis.assessment:
            return None
        try:
            return FinalCaseAssessment.model_validate(analysis.assessment)
        except Exception:  # noqa: BLE001 - a stale row must not block a new run
            return None


def load_analysis(analysis_id: str) -> Optional[AnalysisBundle]:
    with session_scope() as session:
        analysis = AnalysisRepository.get(session, analysis_id)
        if analysis is None:
            return None
        case = CaseRepository.get(session, analysis.case_id)
        return _to_bundle(session, analysis, case.case_number if case else "")


def load_latest_analysis(case_id: str) -> Optional[AnalysisBundle]:
    with session_scope() as session:
        analysis = AnalysisRepository.latest_for_case(session, case_id)
        if analysis is None:
            return None
        case = CaseRepository.get(session, case_id)
        return _to_bundle(session, analysis, case.case_number if case else "")


def _to_bundle(session, analysis: AIAnalysis, case_number: str) -> AnalysisBundle:
    metrics_row = AnalysisRepository.metrics_for_analysis(session, analysis.id)
    review = ReviewRepository.latest_for_analysis(session, analysis.id)

    metrics = (
        AssuranceMetrics(
            groundedness=metrics_row.groundedness,
            evidence_coverage=metrics_row.evidence_coverage,
            unsupported_claim_rate=metrics_row.unsupported_claim_rate,
            contradiction_rate=metrics_row.contradiction_rate,
            source_diversity=metrics_row.source_diversity,
            total_claims=metrics_row.total_claims,
            supported_claims=metrics_row.supported_claims,
            weak_claims=metrics_row.weak_claims,
            unsupported_claims=metrics_row.unsupported_claims,
            contradicted_claims=metrics_row.contradicted_claims,
            reviewer_acceptance=acceptance_score(review.decision) if review else None,
        )
        if metrics_row
        else AssuranceMetrics()
    )

    claims = [
        ValidatedClaim(
            claim_text=row.claim_text,
            claim_type=ClaimType(row.claim_type),
            assurance_status=AssuranceStatus(row.assurance_status),
            confidence_score=row.confidence_score,
            semantic_score=row.semantic_score,
            retrieval_score=row.retrieval_score,
            entailment_score=row.entailment_score,
            model_confidence=row.model_confidence,
            rationale=row.rationale,
            evidence=[
                EvidenceLink(
                    source_id=link.source_id,
                    chunk_id=link.chunk_id,
                    case_id=analysis.case_id,
                    source_type=link.source_type or "document",
                    document_id=link.document_id,
                    document_ref=link.document_ref,
                    document_name=link.document_name,
                    document_date=link.document_date,
                    event_id=link.event_id,
                    event_date=link.event_date,
                    event_type=link.event_type,
                    evidence_text=link.evidence_text,
                    relevance_score=link.relevance_score,
                    cited_by_model=link.cited_by_model,
                )
                for link in sorted(row.evidence, key=lambda e: e.relevance_score, reverse=True)
            ],
        )
        for row in sorted(analysis.claims, key=lambda c: c.claim_index)
    ]

    contradictions = [
        ContradictionFlag(
            conflicting_field=row.conflicting_field,
            description=row.description,
            source_a_id=row.source_a_id,
            source_a_document=row.source_a_document,
            source_a_text=row.source_a_text,
            source_b_id=row.source_b_id,
            source_b_document=row.source_b_document,
            source_b_text=row.source_b_text,
            confidence=row.confidence,
            detector=row.detector,
        )
        for row in analysis.contradictions
    ]

    stored_assessment = analysis.assessment or {}
    assessment = (
        FinalCaseAssessment.model_validate(stored_assessment)
        if stored_assessment
        else FinalCaseAssessment()
    )

    raw: Dict[str, Any] = analysis.raw_output or {}
    output = (
        CaseAnalysisOutput.model_validate(raw)
        if raw
        else CaseAnalysisOutput(executive_summary=analysis.generated_summary)
    )

    return AnalysisBundle(
        analysis_id=analysis.id,
        case_id=analysis.case_id,
        case_number=case_number,
        model_name=analysis.model_name,
        prompt_version=analysis.prompt_version,
        generated_at=analysis.generated_at,
        latency_ms=analysis.latency_ms,
        demo_mode=analysis.demo_mode,
        output=output,
        claims=claims,
        contradictions=contradictions,
        metrics=metrics,
        assessment=assessment,
        retrieved_chunks=[],
    )
